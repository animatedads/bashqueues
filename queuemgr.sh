# Class Wizard: zero-dependency curses-ish class builder
# ---------------------------------------------------------------------------

_queue_mgr_tui_available() {
    [[ -t 0 && -t 1 ]] || return 1
    command -v tput >/dev/null 2>&1 || return 1
    return 0
}

_queue_mgr_tui_read_key() {
    local k rest
    IFS= read -rsn1 k || return 1
    if [[ "$k" == $'\e' ]]; then
        IFS= read -rsn2 -t 0.05 rest || true
        k+="$rest"
    fi
    printf '%s' "$k"
}

_queue_mgr_tui_pick() {
    local title="$1"
    shift
    local -a items=("$@")
    local selected=0
    local key rows cols top max_visible i idx label

    ((${#items[@]} > 0)) || return 1

    if ! _queue_mgr_tui_available; then
        printf '%s\n' "$title" >&2
        select label in "${items[@]}"; do
            [[ -n "$label" ]] || return 1
            printf '%s\n' "$label"
            return 0
        done
    fi

    tput smcup
    tput civis
    stty -echo -icanon time 0 min 0 2>/dev/null || true
    trap 'stty sane 2>/dev/null || true; tput cnorm 2>/dev/null || true; tput rmcup 2>/dev/null || true' RETURN INT TERM

    while true; do
        rows="$(tput lines 2>/dev/null || echo 24)"
        cols="$(tput cols 2>/dev/null || echo 80)"
        max_visible=$((rows - 6))
        ((max_visible < 5)) && max_visible=5

        if (( selected >= max_visible )); then
            top=$((selected - max_visible + 1))
        else
            top=0
        fi

        tput clear
        printf '%s\n' "$title"
        printf '%*s\n' "$cols" '' | tr ' ' '-'
        printf 'Use ↑/↓, Enter to select, q to cancel.\n\n'

        for ((i=0; i<max_visible && top+i<${#items[@]}; i++)); do
            idx=$((top+i))
            label="${items[$idx]}"
            if ((idx == selected)); then
                tput rev
                printf ' > %-.*s' $((cols-4)) "$label"
                tput sgr0
                printf '\n'
            else
                printf '   %-.*s\n' $((cols-4)) "$label"
            fi
        done

        key="$(_queue_mgr_tui_read_key)"
        case "$key" in
            $'\e[A') ((selected > 0)) && selected=$((selected-1)) ;;
            $'\e[B') ((selected < ${#items[@]}-1)) && selected=$((selected+1)) ;;
            "") ;;
            q|Q)
                return 1
                ;;
            $'\n'|$'\r')
                printf '%s\n' "${items[$selected]}"
                return 0
                ;;
        esac
    done
}

_queue_mgr_hint_line_for_facility() {
    local facility="$1"
    local line

    if declare -F _queue_asset_hint_line >/dev/null 2>&1; then
        line="$(_queue_asset_hint_line "$facility" 2>/dev/null || true)"
        [[ -n "$line" ]] && { printf '%s\n' "$line"; return 0; }
    fi

    # Fallback: parse queue asset-hint output.
    line="$(queue asset-hint "$facility" 2>/dev/null | awk '
        /^Target:/ { target=$0 }
        /^Params:/ { params=$0 }
        /^Example:/ { example=$0 }
        /^Notes:/ { notes=$0 }
        END {
            if (target || params || example || notes) {
                print target "\n" params "\n" example "\n" notes
            }
        }')"
    printf '%s\n' "$line"
}

_queue_mgr_list_facilities_compact() {
    queue assets 2>/dev/null | awk '
        /^===/ { next }
        /^$/ { next }
        /^INVALID/ { next }
        /^[[:alnum:]_+-]+:[[:alnum:]_+-]+/ {
            facility=$1
            $1=""
            sub(/^[[:space:]]+/, "")
            printf "%s\t%s\n", facility, $0
        }'
}

_queue_mgr_facility_family() {
    local facility="$1"
    printf '%s\n' "${facility%%:*}"
}

_queue_mgr_facility_check() {
    local facility="$1"
    printf '%s\n' "${facility#*:}"
}

_queue_mgr_wizard_render_preview() {
    local class="$1"
    local allow_parallel="$2"
    local max_concurrent="$3"
    local tmp="$4"
    shift 4
    local -a records=("$@")

    {
        echo "# bashqueues class: $class"
        echo "# Generated by queue mgr class-wizard"
        echo
        echo "CLASS_ALLOW_PARALLEL=$allow_parallel"
        echo "CLASS_MAX_CONCURRENT=$max_concurrent"
        echo
        if [[ -s "$tmp" ]]; then
            cat "$tmp"
            echo
        fi
        printf '%s\n' "${records[@]}"
    }
}

_queue_mgr_class_wizard() {
    local class="${1:-}"
    local allow_parallel=1
    local max_concurrent=0
    local tmp
    local -a records=()
    local -a facilities=()
    local -a menu_items=()
    local choice facility desc family check target params mode record key val
    local editor

    class="${class:-$(_queue_mgr_prompt "Class name")}"
    [[ -n "$class" ]] || { echo "QueueManager: class name required" >&2; return 2; }

    tmp="$(mktemp)"
    trap 'rm -f "$tmp"' RETURN

    while true; do
        echo
        echo "============================================================================="
        echo "CLASS WIZARD: $class"
        echo "============================================================================="
        echo "1. Set execution/concurrency defaults"
        echo "2. Add shared asset check"
        echo "3. Add exclusive asset check"
        echo "4. Add exclusive claim token"
        echo "5. Preview class"
        echo "6. Save class"
        echo "7. Cancel"
        echo
        echo "Current records: ${#records[@]}"
        choice="$(_queue_mgr_prompt "Selection")"

        case "$choice" in
            1)
                allow_parallel="$(_queue_mgr_prompt "CLASS_ALLOW_PARALLEL" "$allow_parallel")"
                max_concurrent="$(_queue_mgr_prompt "CLASS_MAX_CONCURRENT" "$max_concurrent")"

                : > "$tmp"
                echo
                echo "Class defaults. Blank leaves unset."
                val="$(_queue_mgr_prompt "Default runner, e.g. auto/systemd/direct")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_RUNNER=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default working directory")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_WORKING_DIR=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default CPU limit, e.g. 50%")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_CPU_LIMIT=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default memory limit, e.g. 512M")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_MEM_LIMIT=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default max log bytes")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_MAX_LOG_SIZE_BYTES=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default timeout, e.g. 30s")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_TIMEOUT=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default kill-after, e.g. 5s")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_KILL_AFTER=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default billing unit seconds")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_BILLING_UNIT_SECONDS=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default billing cycles")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_BILLING_CYCLES=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default billing grace seconds")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_BILLING_GRACE_SECONDS=%q\n' "$val" >> "$tmp"
                val="$(_queue_mgr_prompt "Default billing policy" "shortest-cap-wins")"; [[ -n "$val" ]] && printf 'CLASS_DEFAULT_BILLING_POLICY=%q\n' "$val" >> "$tmp"
                ;;
            2|3)
                mode="shared"
                [[ "$choice" == "3" ]] && mode="exclusive"

                mapfile -t facilities < <(_queue_mgr_list_facilities_compact)
                menu_items=()
                for facility in "${facilities[@]}"; do
                    menu_items+=("${facility//$'\t'/  -  }")
                done

                facility="$(_queue_mgr_tui_pick "Select asset facility for $mode check" "${menu_items[@]}")" || continue
                facility="${facility%%  -  *}"

                echo
                echo "Selected: $facility"
                echo "-----------------------------------------------------------------------------"
                queue asset-hint "$facility" 2>/dev/null || queue assets explain "$facility" 2>/dev/null || true
                echo "-----------------------------------------------------------------------------"

                family="$(_queue_mgr_facility_family "$facility")"
                check="$(_queue_mgr_facility_check "$facility")"

                target="$(_queue_mgr_prompt "Target for $facility")"
                [[ -n "$target" ]] || { echo "No target supplied; skipped."; continue; }

                params="$(_queue_mgr_prompt "Params as key=value pairs, space separated")"

                if [[ "$mode" == "shared" ]]; then
                    record="queue_class_shared_asset $(_queue_mgr_quote "$family") $(_queue_mgr_quote "$check") $(_queue_mgr_quote "$target")"
                else
                    record="queue_class_exclusive_asset $(_queue_mgr_quote "$family") $(_queue_mgr_quote "$check") $(_queue_mgr_quote "$target")"
                fi

                if [[ -n "$params" ]]; then
                    # Parameters are expected already as shell words. Keep this
                    # explicit so generated class files remain readable.
                    record+=" $params"
                fi

                records+=("$record")
                echo "Added: $record"
                ;;
            4)
                target="$(_queue_mgr_prompt "Exclusive claim token, e.g. github_publish:slot")"
                [[ -n "$target" ]] || continue
                record="queue_class_exclusive_claim $(_queue_mgr_quote "$target")"
                records+=("$record")
                echo "Added: $record"
                ;;
            5)
                _queue_mgr_wizard_render_preview "$class" "$allow_parallel" "$max_concurrent" "$tmp" "${records[@]}"
                _queue_mgr_pause
                ;;
            6)
                mkdir -p "$(_queue_root)/classes"
                local outfile="$(_queue_root)/classes/${class}.env"
                if [[ -f "$outfile" ]]; then
                    if [[ "$(_queue_mgr_prompt "Class exists. Replace? y/N" "N")" != [Yy]* ]]; then
                        continue
                    fi
                    mkdir -p "$(_queue_root)/classes/.backup"
                    cp "$outfile" "$(_queue_root)/classes/.backup/${class}.$(date +%Y%m%d_%H%M%S_%N).env"
                fi

                _queue_mgr_wizard_render_preview "$class" "$allow_parallel" "$max_concurrent" "$tmp" "${records[@]}" > "$outfile"

                if queue classes validate "$class"; then
                    echo "Saved class: $outfile"
                    return 0
                else
                    echo "Saved class failed validation: $outfile" >&2
                    return 1
                fi
                ;;
            7|q|Q)
                return 1
                ;;
            *)
                echo "Unknown selection: $choice"
                ;;
        esac
    done
}


_queue_mgr_panel() {
    local here script
    script="${QUEUEBASH_PANEL_MANAGER:-}"
    if [[ -z "$script" ]]; then
        here="$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd)"
        script="$here/queuemgr_panel.py"
    fi
    [[ -f "$script" ]] || { echo "QueueManager panel script not found: $script" >&2; return 1; }
    export QUEUEBASH_SOURCE="${QUEUEBASH_SOURCE:-$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd)/queuebash.sh}"
    python3 "$script"
}
