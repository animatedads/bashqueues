            5) queue assets validate; _queue_mgr_pause ;;
            6) d="$(_queue_mgr_prompt "Directory")"; queue asset-refresh "$d"; _queue_mgr_pause ;;
            7) fam="$(_queue_mgr_prompt "Family")"; file="$(_queue_mgr_prompt "Plugin file")"; queue assets replace "$fam" "$file"; _queue_mgr_pause ;;
            8) fam="$(_queue_mgr_prompt "Family")"; queue assets rollback "$fam"; _queue_mgr_pause ;;
            9) fam="$(_queue_mgr_prompt "Family")"; queue assets delete "$fam"; _queue_mgr_pause ;;
            10) fam="$(_queue_mgr_prompt "Family")"; queue assets undelete "$fam"; _queue_mgr_pause ;;
            11|q|Q) return 0 ;;
        esac
    done
}

