_queue_mgr_main_menu() {
    while true; do
        _queue_mgr_header "MAIN MENU"
        echo "1. Jobs"
        echo "2. Classes"
        echo "3. Assets"
        echo "4. Workers / Health / Trace"
        echo "5. Exit"
        echo
        read -r -p "Selection: " sel

        case "$sel" in
            1) _queue_mgr_jobs_menu ;;
            2) _queue_mgr_classes_menu ;;
            3) _queue_mgr_assets_menu ;;
            4) _queue_mgr_workers_menu ;;
            5|q|Q|exit) return 0 ;;
        esac
    done
}

_queue_manager() {
    local action="${1:-menu}"
    shift || true

    case "$action" in
        menu|"")
            _queue_mgr_main_menu
            ;;
        jobs)
            _queue_mgr_jobs_menu "$@"
            ;;
        classes|class)
            _queue_mgr_classes_menu "$@"
            ;;
        assets|asset)
            _queue_mgr_assets_menu "$@"
            ;;
        workers|health)
            _queue_mgr_workers_menu "$@"
            ;;
        panel|full|fullscreen|screen)
            _queue_mgr_panel
            ;;
        class-create|create-class)
            local class="${1:-}"
            [[ $# -gt 0 ]] && shift
            _queue_mgr_class_create_noninteractive "$class" "$@"
            ;;
        class-create-interactive|create-class-interactive)
            _queue_mgr_class_create_interactive "${1:-}"
            ;;
        asset-refresh|refresh-assets)
            queue asset-refresh "${1:-}"
            ;;
        class-refresh|refresh-classes)
            queue class-refresh "${1:-}"
            ;;
        hint|asset-hint)
            _queue_mgr_asset_hint "${1:-}"
            ;;
        hints|asset-hints)
            _queue_mgr_asset_hints_list
            ;;
        picker|asset-picker)
            _queue_mgr_facility_picker
            ;;
        help|-h|--help)
            cat <<'EOF'
QueueManager commands:

  queue mgr
  queue manager
  queue qm

Panel manager:
  queue mgr panel
  queue panel

Interactive menus:
  queue mgr jobs
  queue mgr classes
  queue mgr assets
  queue mgr workers

Asset hints:
  queue mgr hints
  queue mgr hint net:http_status
  queue mgr picker

Asset refresh:
  queue assets refresh ./assets.d
  queue asset-refresh ./assets.d
  queue mgr asset-refresh ./assets.d

Class refresh:
  queue classes refresh ./classes
  queue class-refresh ./classes
  queue mgr class-refresh ./classes

Scriptable class creation:
  queue mgr class-create CLASS \
    --no-parallel \
    --max-concurrent 1 \
    --default-runner systemd \
    --default-timeout 30s \
    --default-kill-after 5s \
    --default-max-log-size 1048576 \
    --exclusive-claim github_publish:slot \
    --shared-asset net http_status "https://github.com" timeout=5 \
    --shared-asset git repo_exists "/home/hc3/bashqueues" \
    --shared-asset git branch "/home/hc3/bashqueues" require_branch=main

Record-format only. Legacy CLASS_SHARED_ASSETS is never generated.
EOF
            ;;
        *)
            echo "QueueManager: unknown action: $action" >&2
            echo "Try: queue mgr help" >&2
            return 2
            ;;
    esac
}


