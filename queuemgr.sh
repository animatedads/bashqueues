#!/usr/bin/env bash
# bashqueues QueueManager
#
# Sourced lazily by queuebash.sh. Keeps menu/UI routing out of the core engine.
#
# Design rules:
#   - Do not mutate core queue state directly where a queue command exists.
#   - Generate record-format classes only.
#   - Keep all commands scriptable as well as menu-driven.

_queue_mgr_pause() {
    [[ "${QUEUEBASH_ALLOW_NONINTERACTIVE:-0}" == "1" ]] && return 0
    echo
    read -r -p "Press Enter to continue..." _
}

_queue_mgr_header() {
    local title="$1"
    clear 2>/dev/null || true
    echo "=============================================================================="
    echo "QUEUEBASH MANAGER - $title"
    echo "=============================================================================="
}

_queue_mgr_prompt() {
    local prompt="$1"
    local default="${2:-}"
    local value

    if [[ -n "$default" ]]; then
        read -r -p "$prompt [$default]: " value
        printf '%s\n' "${value:-$default}"
    else
        read -r -p "$prompt: " value
        printf '%s\n' "$value"
    fi
}

_queue_mgr_yesno() {
    local prompt="$1"
    local default="${2:-N}"
    local ans

    read -r -p "$prompt [$default]: " ans
    ans="${ans:-$default}"
    case "${ans,,}" in
        y|yes|1|true) return 0 ;;
        *) return 1 ;;
    esac
}

_queue_mgr_require_class_name() {
    local class="$1"
    if [[ -z "$class" ]]; then
        echo "QueueManager: class name required" >&2
        return 2
    fi
    if [[ ! "$class" =~ ^[A-Za-z_][A-Za-z0-9_-]*$ ]]; then
        echo "QueueManager: invalid class name: $class" >&2
        return 2
    fi
}

_queue_mgr_quote() {
    # Print a Bash-safe representation of one argument.
    printf '%q' "$1"
}


_queue_mgr_asset_hint() {
    local facility="$1"
    local out rc

    if [[ -z "$facility" ]]; then
        echo "Usage: queue mgr hint <family:facility>"
        return 2
    fi

    out="$(queue asset-hint "$facility" 2>/dev/null)"
    rc="$?"

    if [[ "$rc" -eq 0 ]]; then
        printf '%s\n' "$out"
        return 0
    fi

    echo "No published helper hint for: $facility"
    echo
    echo "Use:"
    echo "  queue assets explain $facility"
    echo
    echo "Generic record format:"
    echo "  queue_class_shared_asset FAMILY CHECK \"TARGET\" key=value"
    echo "  queue_class_exclusive_asset FAMILY CHECK \"TARGET\" key=value"
}

_queue_mgr_asset_hints_list() {
    echo "Published helper hints:"
    queue asset-hints 2>/dev/null || true
}

_queue_mgr_facility_picker() {
    echo
    echo "Installed asset facilities:"
    echo "------------------------------------------------------------------------------"
    queue assets 2>/dev/null || true
    echo "------------------------------------------------------------------------------"
    echo
    echo "Published helper hints:"
    _queue_mgr_asset_hints_list | sed 's/^/  /'
    echo
}

_queue_mgr_write_class_file() {
    local class="$1"
    local allow_parallel="$2"
    local max_concurrent="$3"
    local outfile="$4"
    shift 4
    local line

    {
        echo "# bashqueues class: $class"
        echo "# Generated by QueueManager on $(date -Is 2>/dev/null || date)"
        echo
        echo "CLASS_ALLOW_PARALLEL=$allow_parallel"
        echo "CLASS_MAX_CONCURRENT=$max_concurrent"
        echo
        echo "# Record-format assets only."
        echo "#   queue_class_shared_asset family check \"target\" key=value"
        echo "#   queue_class_exclusive_asset family check \"target\" key=value"
        echo "#   queue_class_exclusive_claim \"claim-token\""
        echo

        for line in "$@"; do
            [[ -n "$line" ]] && printf '%s\n' "$line"
        done
    } > "$outfile"
}

_queue_mgr_class_create_noninteractive() {
    local class="$1"
    shift || true

    _queue_mgr_require_class_name "$class" || return "$?"

    local allow_parallel=1
    local max_concurrent=0
    local -a records=()
    local -a default_lines=()
    local family check target mode claim
    local tmp root

    while [[ "$#" -gt 0 ]]; do
        case "$1" in
            --parallel)
                allow_parallel=1
                shift
                ;;
            --no-parallel|--sequential)
                allow_parallel=0
                [[ "$max_concurrent" == "0" ]] && max_concurrent=1
                shift
                ;;
            --max-concurrent)
                [[ $# -ge 2 ]] || { echo "QueueManager: --max-concurrent needs a value" >&2; return 2; }
                max_concurrent="$2"
                [[ "$max_concurrent" =~ ^[0-9]+$ ]] || { echo "QueueManager: max concurrent must be numeric" >&2; return 2; }
                shift 2
                ;;
            --default-runner)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-runner needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_RUNNER=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-cpu-limit)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-cpu-limit needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_CPU_LIMIT=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-mem-limit)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-mem-limit needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_MEM_LIMIT=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-max-log-size)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-max-log-size needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_MAX_LOG_SIZE_BYTES=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-log-policy)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-log-policy needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_LOG_OVERFLOW_POLICY=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-allow-large-log)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-allow-large-log needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_ALLOW_LARGE_LOG=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-timeout)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-timeout needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_TIMEOUT=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-kill-after)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-kill-after needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_KILL_AFTER=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-log-tag)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-log-tag needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_LOG_TAG=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-output-dir)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-output-dir needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_OUTPUT_DIR=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-env-prefix)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-env-prefix needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_ENV_PREFIX=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-cpu-seconds)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-cpu-seconds needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_CPU_SECONDS=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-wall-seconds)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-wall-seconds needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_WALL_SECONDS=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-billing-cycles)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-billing-cycles needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_BILLING_CYCLES=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-billing-unit-seconds)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-billing-unit-seconds needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_BILLING_UNIT_SECONDS=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-billing-grace-seconds)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-billing-grace-seconds needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_BILLING_GRACE_SECONDS=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-billing-policy)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-billing-policy needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_BILLING_POLICY=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --default-working-dir)
                [[ $# -ge 2 ]] || { echo "QueueManager: --default-working-dir needs a value" >&2; return 2; }
                default_lines+=("CLASS_DEFAULT_WORKING_DIR=$(_queue_mgr_quote "$2")")
                shift 2
                ;;
            --exclusive-claim)
                [[ $# -ge 2 ]] || { echo "QueueManager: --exclusive-claim needs a token" >&2; return 2; }
                claim="$2"
                records+=("queue_class_exclusive_claim $(_queue_mgr_quote "$claim")")
                shift 2
                ;;
            --shared-asset|--exclusive-asset)
                mode="$1"
                [[ $# -ge 4 ]] || { echo "QueueManager: $mode requires family check target [params...]" >&2; return 2; }
                family="$2"
                check="$3"
                target="$4"
                shift 4

                local -a params=()
                while [[ "$#" -gt 0 ]]; do
                    case "$1" in
                        --shared-asset|--exclusive-asset|--exclusive-claim|--max-concurrent|--parallel|--no-parallel|--sequential|--replace|--force)
                            break
                            ;;
                        *)
                            params+=("$1")
                            shift
                            ;;
                    esac
                done

                local cmd
                if [[ "$mode" == "--shared-asset" ]]; then
                    cmd="queue_class_shared_asset"
                else
                    cmd="queue_class_exclusive_asset"
                fi

                local rec="$cmd $(_queue_mgr_quote "$family") $(_queue_mgr_quote "$check") $(_queue_mgr_quote "$target")"
                local p
                for p in "${params[@]}"; do
                    rec+=" $(_queue_mgr_quote "$p")"
                done
                records+=("$rec")
                ;;
            --replace|--force)
                # Accepted for readability. queue classes replace is inherently replace-with-backup.
                shift
                ;;
            *)
                echo "QueueManager: unknown class-create option: $1" >&2
                return 2
                ;;
        esac
    done

    root="$(_queue_root)"
    mkdir -p "$root/classes"

    tmp="$(mktemp)"
    _queue_mgr_write_class_file "$class" "$allow_parallel" "$max_concurrent" "$tmp" "${default_lines[@]}" "${records[@]}"

    queue classes replace "$class" "$tmp"
    local rc="$?"
    rm -f "$tmp"
    return "$rc"
}

_queue_mgr_class_create_interactive() {
    local class="${1:-}"
    local allow_parallel max_concurrent tmp root
    local -a records=()
    local -a default_lines=()

    _queue_mgr_header "CLASS CREATE"

    if [[ -z "$class" ]]; then
        class="$(_queue_mgr_prompt "Class name")"
    fi
    _queue_mgr_require_class_name "$class" || return "$?"

    if _queue_mgr_yesno "Allow parallel jobs for this class?" "Y"; then
        allow_parallel=1
        max_concurrent="$(_queue_mgr_prompt "Max concurrent, 0 for unlimited" "0")"
    else
        allow_parallel=0
        max_concurrent="$(_queue_mgr_prompt "Max concurrent" "1")"
    fi

    echo
    echo "Configure class default job settings. Blank keeps unset."
    local v
    v="$(_queue_mgr_prompt "Default runner (auto/systemd/direct)")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_RUNNER=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default CPU limit, e.g. 50%")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_CPU_LIMIT=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default memory limit, e.g. 512M")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_MEM_LIMIT=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default max log bytes")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_MAX_LOG_SIZE_BYTES=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default log overflow policy")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_LOG_OVERFLOW_POLICY=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default timeout, e.g. 30s")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_TIMEOUT=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default kill-after, e.g. 5s")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_KILL_AFTER=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default log tag template" '${JOB_NAME}.${JOB_ID}')"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_LOG_TAG=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default output dir template" '${QUEUEBASH_ROOT}/class_outputs/${JOB_NAME}/${JOB_ID}')"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_OUTPUT_DIR=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default env prefix template" '${JOB_NAME}_${JOB_ID}')"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_ENV_PREFIX=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default working directory")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_WORKING_DIR=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default CPU seconds cap")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_CPU_SECONDS=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default wall seconds cap")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_WALL_SECONDS=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default billing cycles")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_BILLING_CYCLES=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default billing unit seconds, e.g. 60")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_BILLING_UNIT_SECONDS=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default billing grace seconds, e.g. 5")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_BILLING_GRACE_SECONDS=$(_queue_mgr_quote "$v")")
    v="$(_queue_mgr_prompt "Default billing policy" "shortest-cap-wins")"; [[ -n "$v" ]] && default_lines+=("CLASS_DEFAULT_BILLING_POLICY=$(_queue_mgr_quote "$v")")

    echo
    echo "Add exclusive class-level claim tokens, one per line. Blank line ends."
    while true; do
        local claim
        claim="$(_queue_mgr_prompt "Exclusive claim")"
        [[ -z "$claim" ]] && break
        records+=("queue_class_exclusive_claim $(_queue_mgr_quote "$claim")")
    done

    echo
    echo "Add asset checks. Blank family ends."
    echo "Type '?' as the family to list assets/hints."
    while true; do
        local family check target access params rec cmd facility
        family="$(_queue_mgr_prompt "Asset family")"
        [[ -z "$family" ]] && break
        if [[ "$family" == "?" ]]; then
            _queue_mgr_facility_picker
            continue
        fi
        check="$(_queue_mgr_prompt "Facility/check")"
        facility="$family:$check"
        echo
        _queue_mgr_asset_hint "$facility"
        echo
        target="$(_queue_mgr_prompt "Target")"
        access="$(_queue_mgr_prompt "Access shared/exclusive" "shared")"
        params="$(_queue_mgr_prompt "Parameters as key=value words, blank for none")"

        if [[ "${access,,}" == e* ]]; then
            cmd="queue_class_exclusive_asset"
        else
            cmd="queue_class_shared_asset"
        fi

        rec="$cmd $(_queue_mgr_quote "$family") $(_queue_mgr_quote "$check") $(_queue_mgr_quote "$target")"
        if [[ -n "$params" ]]; then
            # Deliberately shell-tokenised here because the user entered a key=value word list.
            # For values containing spaces, use non-interactive class-create.
            local p
            for p in $params; do
                rec+=" $(_queue_mgr_quote "$p")"
            done
        fi
        records+=("$rec")
    done

    root="$(_queue_root)"
    mkdir -p "$root/classes"
    tmp="$(mktemp)"
    _queue_mgr_write_class_file "$class" "$allow_parallel" "$max_concurrent" "$tmp" "${default_lines[@]}" "${records[@]}"

    echo
    echo "Generated class file:"
    echo "------------------------------------------------------------------------------"
    cat "$tmp"
    echo "------------------------------------------------------------------------------"
    echo

    if _queue_mgr_yesno "Save this class?" "Y"; then
        queue classes replace "$class" "$tmp"
    else
        echo "Class not saved."
    fi

    rm -f "$tmp"
}

_queue_mgr_classes_menu() {
    while true; do
        _queue_mgr_header "CLASSES"
        echo "1. List classes"
        echo "2. Show class"
        echo "3. Explain class"
        echo "4. Create class"
        echo "5. Class wizard"
        echo "6. Edit class"
        echo "7. Validate classes"
        echo "8. Refresh classes from directory"
        echo "9. Delete/archive class"
        echo "10. Undelete class"
        echo "11. Back"
        echo
        read -r -p "Selection: " sel

        case "$sel" in
            1) queue classes list; _queue_mgr_pause ;;
            2) c="$(_queue_mgr_prompt "Class")"; queue classes show "$c"; _queue_mgr_pause ;;
            3) c="$(_queue_mgr_prompt "Class")"; queue classes explain "$c"; _queue_mgr_pause ;;
            4) c="$(_queue_mgr_prompt "Class")"; _queue_mgr_class_create_interactive "$c"; _queue_mgr_pause ;;
            5) c="$(_queue_mgr_prompt "Class")"; _queue_mgr_class_wizard "$c"; _queue_mgr_pause ;;
            6) c="$(_queue_mgr_prompt "Class")"; queue classes edit "$c"; _queue_mgr_pause ;;
            7) queue classes validate; _queue_mgr_pause ;;
            8) d="$(_queue_mgr_prompt "Directory")"; queue classes refresh "$d"; _queue_mgr_pause ;;
            9) c="$(_queue_mgr_prompt "Class")"; queue classes delete "$c"; _queue_mgr_pause ;;
            10) c="$(_queue_mgr_prompt "Class")"; queue classes undelete "$c"; _queue_mgr_pause ;;
            11|q|Q) return 0 ;;
        esac
    done
}

_queue_mgr_assets_menu() {
    while true; do
        _queue_mgr_header "ASSETS"
        echo "1. List asset facilities"
        echo "2. Explain facility"
        echo "3. Hint for facility"
        echo "4. List built-in hints"
        echo "5. Validate plugins"
        echo "6. Refresh plugins from directory"
        echo "7. Replace plugin"
        echo "8. Rollback plugin"
        echo "9. Delete/archive plugin"
        echo "10. Undelete plugin"
        echo "11. Back"
        echo
        read -r -p "Selection: " sel

        case "$sel" in
            1) queue assets; _queue_mgr_pause ;;
            2) f="$(_queue_mgr_prompt "Facility, e.g. net:http_status")"; queue assets explain "$f"; _queue_mgr_pause ;;
            3) f="$(_queue_mgr_prompt "Facility, e.g. net:http_status")"; _queue_mgr_asset_hint "$f"; _queue_mgr_pause ;;
